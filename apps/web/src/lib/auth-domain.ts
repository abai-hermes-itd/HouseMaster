// ── isAllowedDomain ──────────────────────────────────────────────────────────
// Домен-проверка для Admin-контура (ADR-0004, раздел «Решение», п.2).
// Алгоритм не меняется при переходе на несколько доменов или хранение в БД —
// меняется только источник данных (сегодня — config, завтра — БД).
//
// Вынесено из lib/auth.ts в отдельный модуль без зависимостей от next-auth/next,
// чтобы функцию можно было юнит-тестировать без загрузки Next.js рантайма
// (HM-005-QA1). Поведение идентично прежней версии, замыкавшейся на
// process.env.ALLOWED_WORKSPACE_DOMAIN — теперь домен передаётся явным
// параметром вместо чтения из замыкания.
export function isAllowedDomain(
  hd: string | undefined,
  allowedDomain: string,
): boolean {
  if (!hd) return false; // личный Gmail — hd отсутствует
  return hd === allowedDomain;
}
